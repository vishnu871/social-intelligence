function createRemainingRecommendations() {
  const themes = [
    "Longevity, Retirement & Longer Lives",
    "Life Transitions & Reinvention",
    "Wealth, Planning & Life Decisions",
    "Midlife, Purpose & Identity",
    "Community, Reflection & Zest Circle",
    "Events & Zuva Updates",
  ];

  const platforms = ["Facebook", "Instagram", "LinkedIn"];
  const formats = ["Single Image", "Carousel", "Text Post"];

  const hooks = [
    "What becomes possible when you stop following the old timeline?",
    "The next chapter doesn't need to look like the last one.",
    "Sometimes clarity begins with a better question.",
    "Your experience may be the beginning of something new.",
    "What would you choose if you had more room to explore?",
    "A meaningful life is not a finished formula.",
  ];

  const records = [...baseRecommendations];

  for (let rank = 7; rank <= 21; rank += 1) {
    const index = rank - 7;
    const theme = themes[index % themes.length];
    const platform = platforms[index % platforms.length];
    const format = formats[index % formats.length];

    const dateIndex = index % 7;
    const dates = [
      "2026-09-14",
      "2026-09-15",
      "2026-09-16",
      "2026-09-17",
      "2026-09-18",
      "2026-09-19",
      "2026-09-20",
    ];

    const date = dates[dateIndex];

    const record = {
      recommendation_rank_v1: rank,
      production_id_v1: `ZL-P${String(rank).padStart(3, "0")}`,
      content_brief_id_v1: `CB-${String(rank).padStart(3, "0")}`,
      approval_id_v1: `APR-${String(rank).padStart(3, "0")}`,
      date,
      day: new Date(`${date}T12:00:00`).toLocaleDateString("en-US", {
        weekday: "long",
      }),
      hour: platform === "LinkedIn" ? 11 : platform === "Instagram" ? 19 : 13,
      platform,
      content_type: format,
      theme,
      final_opportunity_score_v3: Number(
        (78.95 - (rank - 7) * 0.42).toFixed(4)
      ),
      historical_opportunity_v3: Number(
        (77.8 - (rank - 7) * 0.3).toFixed(4)
      ),
      historical_evidence_strength_v3: Number(
        (0.86 - (index % 4) * 0.025).toFixed(3)
      ),
      historical_evidence_coverage_v3: 1,
      current_signal_class_v1:
        index % 4 === 0 ? "WATCH" : index % 3 === 0 ? "MODERATE POSITIVE" : "NO SIGNAL",
      current_world_relevance_v3: Number(
        (0.55 + (index % 5) * 0.08).toFixed(2)
      ),
      decision_v3: "SELECT",
      qa_status: index % 3 === 0 ? "NEEDS_REVIEW" : "PASS",
      manual_review_required_v1: index % 3 === 0,
      production_readiness_v1:
        index % 3 === 0 ? "REVIEW" : "READY",
      hook_v1: hooks[index % hooks.length],
      caption_v1:
        "A thoughtful social perspective from Zuva Life on living, working and growing through the different chapters of life.",
      cta_v1: "What does this make you think about?",
      creative_direction_v1:
        "Clean editorial visual language with generous whitespace and human-centered imagery.",
    };

    records.push(record);
  }

  return records;
}

export { baseRecommendations, createRemainingRecommendations };

export default createRemainingRecommendations();