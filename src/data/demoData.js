function createRecommendation(index) {
  const rank = index + 1;
  const theme = themes[index % themes.length];
  const platform = platforms[index % platforms.length];
  const contentType = contentTypes[index % contentTypes.length];
  const day = days[index % days.length];

  const hour =
    platform === "LinkedIn"
      ? 11 + (index % 3)
      : platform === "Facebook"
        ? 12 + (index % 3)
        : 18 + (index % 3);

  const score = Math.max(
    68.5961,
    78.8 - index * 0.38 + ((index * 17) % 9) / 10
  );

  const evidenceStrength = Math.min(
    0.92,
    Math.max(0.72, 0.82 + ((index * 7) % 12) / 100)
  );

  const signal =
    index % 5 === 0
      ? "MODERATE POSITIVE"
      : index % 5 === 2
        ? "WATCH"
        : "NO SIGNAL";

  const date = `2026-09-${String(14 + Math.floor(index / 3)).padStart(
    2,
    "0"
  )}`;

  return {
    recommendation_rank_v1: rank,
    production_id_v1: `ZL-PROD-${String(rank).padStart(3, "0")}`,
    content_brief_id_v1: `ZL-BRIEF-${String(rank).padStart(3, "0")}`,
    approval_id_v1: `ZL-APP-${String(rank).padStart(3, "0")}`,
    date,
    day,
    hour,
    platform,
    content_type: contentType,
    theme,
    final_opportunity_score_v3: Number(score.toFixed(4)),
    historical_opportunity_v3: Number((score / 90).toFixed(4)),
    historical_evidence_strength_v3: Number(
      evidenceStrength.toFixed(4)
    ),
    historical_evidence_coverage_v3: 1,
    current_signal_class_v1: signal,
    current_world_relevance_v3: Number(
      (0.65 + ((index * 11) % 28) / 100).toFixed(4)
    ),
    decision_v3: "SELECTED",
    qa_status: index % 4 === 2 ? "PASS" : "NEEDS_REVIEW",
    manual_review_required_v1:
      index % 4 === 2 ? "No" : "Yes",
    production_readiness_v1:
      index % 4 === 2 ? "Ready" : "Review Required",
    hook_v1: hooks[index % hooks.length],
    caption_v1: captions[index % captions.length],
    cta_v1: ctas[index % ctas.length],
    creative_direction_v1:
      creativeDirections[index % creativeDirections.length],
  };
}

export function createRemainingRecommendations() {
  const generated = [];

  for (let index = 6; index < 21; index += 1) {
    generated.push(createRecommendation(index));
  }

  return [...baseRecommendations, ...generated];
}

